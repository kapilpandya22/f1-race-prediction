from openai import OpenAI
from prediction_tool import PredictionTool

client = OpenAI(
    base_url="http://127.0.0.1:1234/v1",
    api_key="lm-studio"
)

tool = PredictionTool()

top3 = tool.get_top_predictions(
    race_name="Australian Grand Prix",
    model="logistic",
    top_n=3
)

prompt = f"""
You are an F1 prediction analyst.

The following are podium predictions generated by a machine learning model:

{top3}

Explain:
1. Who is predicted to finish on the podium.
2. Their podium probabilities.
3. Which driver appears strongest.

Keep the answer short.
"""

response = client.chat.completions.create(
    model="qwen2.5-3b-instruct.gguf",
    messages=[
        {
            "role": "user",
            "content": prompt
        }
    ],
    temperature=0.1
)

print(response.choices[0].message.content)